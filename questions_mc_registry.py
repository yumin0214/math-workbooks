def get_mc_question(qid: str):
    """Retrieve question definition by QID (native or variant)."""
    if qid in MC_QUESTIONS:
        return dict(MC_QUESTIONS[qid])
    for variants in MC_REPLACEMENT_VARIANTS.values():
        for v in variants:
            if v["variant_id"] == qid:
                return dict(v)
    return None


def get_native_unit_questions(unit: int):
    """Returns all 15 native questions for a unit sorted by slot_number 1..15."""
    qs = [q for q in MC_QUESTIONS.values() if q["unit"] == unit]
    return sorted(qs, key=lambda x: x["slot_number"])


def get_replacement_variants_for_slot(unit: int, native_qid: str):
    """Returns candidate replacement variants for a given native slot."""
    return MC_REPLACEMENT_VARIANTS.get(native_qid, [])


def sanitize_question_for_client(q_dict: dict) -> dict:
    """
    Returns public representation safe for browser delivery.
    Strips authoritative_answer_payload and grading_rule_key.
    """
    clean = dict(q_dict)
    clean.pop("authoritative_answer_payload", None)
    clean.pop("grading_rule_key", None)
    return clean
